import React, { useState } from 'react';
import { Terminal, Copy, Check, Download, FileCode, Layers, Info } from 'lucide-react';
import { downloadAsFile } from '../utils/commandBuilder';

interface CliCommandViewProps {
  commandString: string;
  url: string;
  quality: string;
  format: string;
  destinationFolder: string;
  customFolder?: string;
  embedSubtitles?: boolean;
  embedThumbnail?: boolean;
  addMetadata?: boolean;
  sponsorblock?: boolean;
}

export const CliCommandView: React.FC<CliCommandViewProps> = ({
  commandString,
  url,
  quality,
  format,
  destinationFolder,
  customFolder,
  embedSubtitles,
  embedThumbnail,
  addMetadata,
  sponsorblock,
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    navigator.clipboard.writeText(commandString);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadSh = () => {
    const targetPath = destinationFolder === 'custom' && customFolder ? customFolder : `~/Downloads/${destinationFolder}`;
    const content = `#!/usr/bin/env bash
# Generated by yt-dlp GUI Frontend
# Target directory: ${targetPath}

set -e

echo "==> Preparing download destination: ${targetPath}"
mkdir -p "${targetPath}"

echo "==> Executing yt-dlp..."
${commandString}

echo "==> Download complete!"
`;
    downloadAsFile('ytdlp_download.sh', content, 'application/x-sh');
  };

  const handleDownloadBat = () => {
    const targetPath = destinationFolder === 'custom' && customFolder ? customFolder : `%USERPROFILE%\\Downloads\\${destinationFolder}`;
    const content = `@echo off
REM Generated by yt-dlp GUI Frontend
REM Target directory: ${targetPath}

echo Preparing download destination...
if not exist "${targetPath}" mkdir "${targetPath}"

echo Executing yt-dlp...
${commandString}

echo Download finished!
pause
`;
    downloadAsFile('ytdlp_download.bat', content, 'application/x-bat');
  };

  return (
    <div className="bg-neutral-900 border border-neutral-800 rounded-xl p-4 sm:p-6 mb-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 mb-4">
        <div>
          <h3 className="text-base font-semibold text-neutral-100 flex items-center gap-2">
            <Terminal className="w-5 h-5 text-red-500" />
            <span>Interactive CLI Generator</span>
          </h3>
          <p className="text-xs text-neutral-400 mt-0.5">
            Real-time CLI command generated from your 1-click selections. Run directly in any terminal or save as a script.
          </p>
        </div>

        <div className="flex items-center gap-2 flex-wrap">
          <button
            type="button"
            onClick={handleCopy}
            className="px-3 py-1.5 bg-neutral-800 hover:bg-neutral-700 text-neutral-200 border border-neutral-700 rounded-lg text-xs font-medium transition-colors flex items-center gap-1.5"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Copied!' : 'Copy Command'}</span>
          </button>

          <button
            type="button"
            onClick={handleDownloadSh}
            className="px-3 py-1.5 bg-neutral-800 hover:bg-neutral-700 text-neutral-200 border border-neutral-700 rounded-lg text-xs font-medium transition-colors flex items-center gap-1.5"
            title="Download script for macOS / Linux"
          >
            <Download className="w-3.5 h-3.5 text-blue-400" />
            <span>Export .sh</span>
          </button>

          <button
            type="button"
            onClick={handleDownloadBat}
            className="px-3 py-1.5 bg-neutral-800 hover:bg-neutral-700 text-neutral-200 border border-neutral-700 rounded-lg text-xs font-medium transition-colors flex items-center gap-1.5"
            title="Download batch file for Windows"
          >
            <Download className="w-3.5 h-3.5 text-amber-400" />
            <span>Export .bat</span>
          </button>
        </div>
      </div>

      {/* Code Display */}
      <div className="relative bg-neutral-950 border border-neutral-800 rounded-lg p-3.5 font-mono text-xs text-neutral-200 leading-relaxed overflow-x-auto select-all">
        <code className="text-red-400 font-bold">yt-dlp </code>
        <span>{commandString.replace('yt-dlp ', '')}</span>
      </div>

      {/* Flag Breakdown Matrix */}
      <div className="mt-4 pt-4 border-t border-neutral-800">
        <div className="text-xs font-semibold text-neutral-300 uppercase tracking-wider mb-2.5 flex items-center gap-1.5">
          <Layers className="w-3.5 h-3.5 text-neutral-400" />
          <span>Active Flag Breakdown</span>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-2 text-xs">
          <div className="p-2.5 bg-neutral-950/60 border border-neutral-800/80 rounded-lg">
            <span className="font-mono text-amber-400 font-semibold">-f / -x</span>
            <span className="text-neutral-400 ml-2">
              {quality === 'audio-only'
                ? 'Extracts audio track with specified codec'
                : `Filters streams up to ${quality === 'best' ? 'max' : quality + 'p'} resolution`}
            </span>
          </div>

          <div className="p-2.5 bg-neutral-950/60 border border-neutral-800/80 rounded-lg">
            <span className="font-mono text-amber-400 font-semibold">--merge-output-format</span>
            <span className="text-neutral-400 ml-2">
              Remuxes video + audio streams into clean <span className="font-mono text-neutral-200">{format}</span> container
            </span>
          </div>

          <div className="p-2.5 bg-neutral-950/60 border border-neutral-800/80 rounded-lg">
            <span className="font-mono text-amber-400 font-semibold">-P / -o</span>
            <span className="text-neutral-400 ml-2">
              Sets destination directory and templated title naming
            </span>
          </div>

          {embedThumbnail && (
            <div className="p-2.5 bg-neutral-950/60 border border-neutral-800/80 rounded-lg">
              <span className="font-mono text-amber-400 font-semibold">--embed-thumbnail</span>
              <span className="text-neutral-400 ml-2">
                Attaches cover art directly into the media container
              </span>
            </div>
          )}

          {addMetadata && (
            <div className="p-2.5 bg-neutral-950/60 border border-neutral-800/80 rounded-lg">
              <span className="font-mono text-amber-400 font-semibold">--add-metadata</span>
              <span className="text-neutral-400 ml-2">
                Injects title, artist, year, and chapter tags
              </span>
            </div>
          )}

          {embedSubtitles && (
            <div className="p-2.5 bg-neutral-950/60 border border-neutral-800/80 rounded-lg">
              <span className="font-mono text-amber-400 font-semibold">--embed-subs</span>
              <span className="text-neutral-400 ml-2">
                Downloads and muxes soft subtitle streams
              </span>
            </div>
          )}

          {sponsorblock && (
            <div className="p-2.5 bg-neutral-950/60 border border-neutral-800/80 rounded-lg">
              <span className="font-mono text-amber-400 font-semibold">--sponsorblock-remove</span>
              <span className="text-neutral-400 ml-2">
                Cuts sponsor segments automatically using SponsorBlock API
              </span>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
